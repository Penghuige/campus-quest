#!/usr/bin/env bash
# Canonical SUT bring-up for the load-test suite (plan Task 1;
# spec: docs/superpowers/specs/2026-10-29-load-testing-design.md §Env).
#
# Run via `make loadtest-stack-up` — the Makefile injects TEST_STACK_ENV.
# Pinned SUT shape (recorded into SUT-SHAPE.md on every up):
#   uvicorn app.main:create_app --factory --port 8000 --workers 2
#   celery -A app.workers.celery_app:celery_app worker (default concurrency)
#   celery -A app.workers.celery_app:celery_app beat (recruitment scans)
# Never point this at production: the guard below refuses non-local
# database hosts (spec §Non-goals: production serves real tasks).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

LOG_DIR="$REPO_ROOT/backend/loadtest/runs/stack-logs"
SHAPE_FILE="$REPO_ROOT/backend/loadtest/SUT-SHAPE.md"

require_local_stack() {
  local missing=0
  local var
  for var in DATABASE_URL REDIS_URL S3_ENDPOINT_URL S3_BUCKET \
             S3_ACCESS_KEY S3_SECRET_KEY BUSINESS_TIMEZONE; do
    if [[ -z "${!var:-}" ]]; then
      echo "loadtest-stack: $var is not set — run via 'make loadtest-stack-up'" >&2
      missing=1
    fi
  done
  [[ "$missing" -eq 0 ]] || exit 2
  if [[ ! "$DATABASE_URL" =~ ^(postgresql\+asyncpg://[^@]*@)(localhost|127\.0\.0\.1)(:|[/?]) ]]; then
    echo "loadtest-stack: refusing non-local DATABASE_URL (spec: never production)" >&2
    exit 3
  fi
}

stack_up() {
  require_local_stack
  if [[ -f "$LOG_DIR/uvicorn.pid" ]] \
     && kill -0 "$(cat "$LOG_DIR/uvicorn.pid")" 2>/dev/null; then
    echo "loadtest-stack: already up (uvicorn pid $(cat "$LOG_DIR/uvicorn.pid"));" \
         "run 'make loadtest-stack-down' first" >&2
    exit 4
  fi
  if curl -s -o /dev/null --max-time 2 "http://localhost:8000/"; then
    echo "loadtest-stack: port 8000 already serving (e2e stack?) — stop it first" >&2
    exit 5
  fi
  mkdir -p "$LOG_DIR"

  docker compose -f infra/docker-compose.yml up -d
  uv run --directory backend alembic upgrade head

  : >"$LOG_DIR/env.txt"
  local var
  for var in DATABASE_URL REDIS_URL S3_ENDPOINT_URL S3_BUCKET BUSINESS_TIMEZONE; do
    echo "$var=${!var}" >>"$LOG_DIR/env.txt"
  done

  start_bg uvicorn \
    uv run --directory backend uvicorn app.main:create_app \
    --factory --port 8000 --workers 2
  start_bg celery \
    uv run --directory backend celery -A app.workers.celery_app:celery_app \
    worker --loglevel=INFO
  start_bg beat \
    uv run --directory backend celery -A app.workers.celery_app:celery_app \
    beat --loglevel=INFO

  cat >"$SHAPE_FILE" <<'EOF'
# SUT shape (generated by backend/loadtest/stack.sh — do not edit)

- API: `uvicorn app.main:create_app --factory --port 8000 --workers 2`
- Async: `celery -A app.workers.celery_app:celery_app worker` (default concurrency) + `beat`
  (recruitment-scan schedule, app/workers/celery_app.py `_beat_schedule`)
- Stack: `infra/docker-compose.yml` — postgres:16 on :15432, redis:7 on :6379,
  minio on :9000
- Load generation: single locust process on the same host (spec §Non-goals)
EOF
  echo "loadtest-stack: up — logs in backend/loadtest/runs/stack-logs/"
}

start_bg() { # name command...
  local name="$1"
  shift
  nohup "$@" >"$LOG_DIR/$name.log" 2>&1 &
  echo $! >"$LOG_DIR/$name.pid"
  echo "loadtest-stack: $name started (pid $(cat "$LOG_DIR/$name.pid"))"
}

stop_one() { # name
  local pid_file="$LOG_DIR/$1.pid"
  [[ -f "$pid_file" ]] || return 0
  local pid
  pid="$(cat "$pid_file")"
  if kill -0 "$pid" 2>/dev/null; then
    kill -TERM "$pid" 2>/dev/null || true
    local i
    for i in 1 2 3 4 5; do
      kill -0 "$pid" 2>/dev/null || break
      sleep 1
    done
    if kill -0 "$pid" 2>/dev/null; then
      kill -KILL "$pid" 2>/dev/null || true
    fi
  fi
  rm -f "$pid_file"
}

stack_down() {
  stop_one beat
  stop_one celery
  stop_one uvicorn
  docker compose -f infra/docker-compose.yml down
  echo "loadtest-stack: down (volumes kept; seed with --force for a fresh world)"
}

case "${1:-}" in
  up) stack_up ;;
  down) stack_down ;;
  *)
    echo "usage: stack.sh up|down (via make loadtest-stack-up/-down)" >&2
    exit 64
    ;;
esac
