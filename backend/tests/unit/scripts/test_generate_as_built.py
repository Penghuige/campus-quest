# backend/tests/unit/scripts/test_generate_as_built.py
"""The as-built map's freshness check.

``--check`` is a wired gate (``make arch-map-check`` in pre-push and
CI). A gate that reds on EVERY commit would be noise: the generated
map stamps the HEAD it was rendered from, so a byte-exact comparison
flags a fresh map the moment any later commit lands. The check
therefore compares the SCANNED CONTENT with the HEAD stamp normalized
out — the stamp stays informational in the file, but only real tree
drift fails the gate.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from typing import Any

import pytest

_SCRIPT = Path(__file__).resolve().parents[4] / "scripts" / "generate_as_built.py"


def _load_generator() -> Any:
    spec = importlib.util.spec_from_file_location(
        "generate_as_built_under_test", _SCRIPT
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def generator() -> Any:
    return _load_generator()


def test_check_freshness_ignores_the_head_stamp(generator: Any) -> None:
    """The same scanned content under two different HEAD stamps is
    FRESH — the stamp records provenance, not drift."""
    text_a = (
        "# CampusQuest As-Built Architecture Map\n"
        "<!-- AUTO-GENERATED by scripts/generate_as_built.py (make arch-map).\n"
        "     the tree as it is. Generated from HEAD aaabbb1. -->\n"
        "body\n"
    )
    text_b = text_a.replace("HEAD aaabbb1", "HEAD cccddd2")
    assert generator.check_freshness(text_a, text_a)
    assert generator.check_freshness(text_a, text_b)


def test_check_freshness_fails_on_real_drift(generator: Any) -> None:
    """Any content difference beyond the stamp line is staleness."""
    text_a = "header\n<!-- from HEAD aaabbb1 -->\nbody-one\n"
    text_b = "header\n<!-- from HEAD cccddd2 -->\nbody-two\n"
    assert not generator.check_freshness(text_a, text_b)


def test_check_cli_passes_on_stamp_only_difference(tmp_path: Path) -> None:
    """End to end: a committed map whose only difference from the
    freshly scanned tree is the HEAD stamp passes ``--check`` (exit 0);
    one drifted line fails it (exit 1)."""
    generator = _load_generator()
    saved = {
        "BACKEND_APP": generator.BACKEND_APP,
        "FRONTEND_SRC": generator.FRONTEND_SRC,
        "REPO_ROOT": generator.REPO_ROOT,
        "OUT_PATH": generator.OUT_PATH,
    }
    empty_app = tmp_path / "app"
    (empty_app / "modules").mkdir(parents=True)
    empty_src = tmp_path / "src"
    empty_src.mkdir()
    generator.BACKEND_APP = empty_app
    generator.FRONTEND_SRC = empty_src
    generator.REPO_ROOT = tmp_path
    generator.OUT_PATH = tmp_path / "as-built.md"
    try:
        fresh = generator.render(
            generator.backend_scan(), {}, generator.backend_module_file_stats()
        )
        generator.OUT_PATH.write_text(
            fresh.replace("HEAD ", "HEAD oldstamp-"), encoding="utf-8"
        )
        assert generator.main(["--check"]) == 0

        drifted = fresh + "\nan extra boundary line\n"
        generator.OUT_PATH.write_text(drifted, encoding="utf-8")
        assert generator.main(["--check"]) == 1
    finally:
        for key, value in saved.items():
            setattr(generator, key, value)
